"""The ``backend-builder`` command: the one launcher for every process.

Each command takes an app by package name, imports it, reads its ``app``
object and derives what to run from it.
"""

from __future__ import annotations

import asyncio
import importlib
import json
import os
from typing import Any

import typer

from backend_builder import metrics, migrations
from backend_builder.app import App
from backend_builder.engine import run
from backend_builder.log import configure, get_logger
from backend_builder.settings import DATABASE_URL, Settings, SettingsError

cli = typer.Typer(no_args_is_help=True, add_completion=False)

logger = get_logger(__name__)

APP_ENV = "BACKEND_BUILDER_APP"


def settings() -> Settings:
    try:
        return Settings.from_env()
    except SettingsError as exc:
        raise typer.BadParameter(str(exc)) from exc


def database_url(url: str | None) -> str:
    resolved = url or settings().database_url
    if not resolved:
        raise typer.BadParameter(f"pass --url or set {DATABASE_URL}")
    return resolved


def load_app(package: str) -> App:
    """Import ``package`` and return its ``app``."""
    try:
        module = importlib.import_module(package)
    except ModuleNotFoundError as exc:
        raise typer.BadParameter(f"cannot import {package!r}: {exc}") from exc
    found = getattr(module, "app", None)
    if not isinstance(found, App):
        raise typer.BadParameter(f"{package!r} has no App named 'app'")
    return found


def http_factory() -> Any:
    """Uvicorn factory for reload mode; the app comes from the environment."""
    return load_app(os.environ[APP_ENV]).http()


@cli.command()
def serve(
    package: str,
    host: str = "127.0.0.1",
    port: int = 8000,
    reload: bool = False,
    log_level: str | None = None,
) -> None:
    """Serve an app's endpoints over HTTP. The store comes from the settings."""
    import uvicorn

    current = settings()
    configure((log_level or current.log_level).upper())
    app = load_app(package)
    logger.info(
        "serving app=%s env=%s store=%s host=%s port=%d",
        app.name,
        current.runtime_env,
        current.store_name,
        host,
        port,
    )
    if reload:
        os.environ[APP_ENV] = package
        uvicorn.run(
            "backend_builder.cli:http_factory", factory=True, host=host, port=port, reload=True
        )
        return

    http = app.http()
    store = app.check_store(app.create_store())

    async def main() -> None:
        api = uvicorn.Server(uvicorn.Config(http, host=host, port=port))
        await asyncio.gather(api.serve(), metrics.serve(current.metrics_port, store.ping))

    asyncio.run(main())


@cli.command()
def trigger(
    package: str,
    reaction: str,
    input: str = "{}",
    log_level: str | None = None,
) -> None:
    """Run one of an app's reactions by qualified name with a JSON input."""
    configure((log_level or settings().log_level).upper())
    app = load_app(package)
    parsed: Any = json.loads(input)
    if not isinstance(parsed, dict):
        raise typer.BadParameter("input must be a JSON object")
    payload: dict[str, Any] = {str(k): v for k, v in parsed.items()}  # type: ignore[union-attr]
    ctx = asyncio.run(
        run(
            app.check_store(app.create_store()),
            app.resolve(reaction),
            payload,
            max_attempts=app.max_attempts,
            timeout=app.timeout,
            triggers=app.triggers,
            source="cli",
            records=settings().run_records,
        )
    )
    typer.echo(f"reaction_id={ctx.reaction_id} total_ms={ctx.trace.total_ms():.1f}")


@cli.command()
def graph(package: str) -> None:
    """Print an app's entities, reactions and endpoints."""
    app = load_app(package)
    for section, items in app.describe().items():
        typer.echo(f"{section}:")
        for item in items:
            typer.echo(f"  {item}")


@cli.command()
def makemigration(
    package: str,
    message: str = typer.Option(..., "-m", "--message"),
    empty: bool = False,
    url: str | None = None,
    log_level: str | None = None,
) -> None:
    """Write a migration: autogenerated from entity changes, or --empty for SQL."""
    configure((log_level or settings().log_level).upper())
    app = load_app(package)
    try:
        path = migrations.makemigration(app, database_url(url), message, empty=empty)
    except migrations.MigrationError as exc:
        raise typer.BadParameter(str(exc)) from exc
    typer.echo(str(path))


@cli.command()
def migrate(
    package: str,
    check: bool = False,
    url: str | None = None,
    log_level: str | None = None,
) -> None:
    """Apply pending migrations. With --check, verify entities match the chain instead."""
    configure((log_level or settings().log_level).upper())
    app = load_app(package)
    try:
        if check:
            migrations.check(app, database_url(url))
            typer.echo("entities match migrations")
        else:
            migrations.migrate(app, database_url(url))
    except migrations.MigrationError as exc:
        typer.echo(str(exc), err=True)
        raise typer.Exit(code=1) from exc


@cli.command()
def worker(package: str, once: bool = False, log_level: str | None = None) -> None:
    """Deliver outbox rows: claim, run, ack. Polls forever unless --once."""
    from backend_builder.worker import Worker

    current = settings()
    configure((log_level or current.log_level).upper())
    app = load_app(package)
    store = app.check_store(app.create_store())
    worker = Worker(app, store, current)
    if once:
        claimed = asyncio.run(worker.run_once())
        typer.echo(f"claimed={claimed}")
        return

    async def main() -> None:
        await asyncio.gather(worker.run_forever(), metrics.serve(current.metrics_port, store.ping))

    try:
        asyncio.run(main())
    except KeyboardInterrupt:
        pass


@cli.command()
def scheduler(package: str, once: bool = False, log_level: str | None = None) -> None:
    """Keep each schedule's next occurrence in the outbox. Ticks forever unless --once."""
    from backend_builder.scheduler import Scheduler

    current = settings()
    configure((log_level or current.log_level).upper())
    app = load_app(package)
    store = app.check_store(app.create_store())
    scheduler = Scheduler(app, store, current)
    if once:
        seeded = asyncio.run(scheduler.tick())
        typer.echo(f"seeded={seeded}")
        return

    async def main() -> None:
        await asyncio.gather(
            scheduler.run_forever(), metrics.serve(current.metrics_port, store.ping)
        )

    try:
        asyncio.run(main())
    except KeyboardInterrupt:
        pass


@cli.command()
def admin(
    package: str, host: str = "127.0.0.1", port: int | None = None, log_level: str | None = None
) -> None:
    """Serve the admin console: graph, reactions, runs, outbox, schedules."""
    import uvicorn

    from backend_builder.admin import create_admin_app

    current = settings()
    configure((log_level or current.log_level).upper())
    app = load_app(package)
    store = app.check_store(app.create_store())
    console = create_admin_app(app, store, token=current.admin_token)
    logger.info(
        "admin console app=%s host=%s port=%d token=%s",
        app.name,
        host,
        port or current.admin_port,
        "required" if current.admin_token else "none",
    )
    uvicorn.run(console, host=host, port=port or current.admin_port)


@cli.command()
def outbox(package: str) -> None:
    """Print outbox depth: pending, claimed and dead rows, and the oldest pending."""
    app = load_app(package)
    stats = asyncio.run(app.create_store().outbox_stats())
    typer.echo(f"pending={stats.pending} claimed={stats.claimed} dead={stats.dead}")
    typer.echo(
        f"oldest_pending={stats.oldest_pending.isoformat() if stats.oldest_pending else None}"
    )


def main() -> None:
    cli()
