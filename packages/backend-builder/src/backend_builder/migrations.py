"""Alembic, driven from an App.

An app's migrations live in one chain under its ``migrations`` directory.
``makemigration`` autogenerates a migration from entity changes, or scaffolds
an empty one for hand-written SQL. ``migrate`` applies the chain. ``check``
fails if entities differ from what the chain produces.

Autogenerate compares tables and columns only. Constraints, indexes and every
other database feature are written by hand into migrations, so they are
excluded from comparison and never dropped as "undeclared".
"""

from __future__ import annotations

import asyncio
import io
from pathlib import Path
from typing import TYPE_CHECKING, Any

from alembic import command
from alembic.config import Config
from alembic.util.exc import AutogenerateDiffsDetected, CommandError
from sqlalchemy.engine import Connection, make_url
from sqlalchemy.ext.asyncio import create_async_engine

from backend_builder.log import get_logger

if TYPE_CHECKING:
    from backend_builder.app import App

logger = get_logger(__name__)

ENV_PY = '''"""Written by backend-builder. The App supplies the metadata; do not edit."""

from alembic import context

from backend_builder.migrations import run_env

run_env(context)
'''

SCRIPT_MAKO = '''"""${message}

Revision ID: ${up_revision}
Revises: ${down_revision | comma,n}
Create Date: ${create_date}
"""

from collections.abc import Sequence

import sqlalchemy as sa
from alembic import op
${imports if imports else ""}
revision: str = ${repr(up_revision)}
down_revision: str | None = ${repr(down_revision)}
branch_labels: str | Sequence[str] | None = ${repr(branch_labels)}
depends_on: str | Sequence[str] | None = ${repr(depends_on)}


def upgrade() -> None:
    ${upgrades if upgrades else "pass"}


def downgrade() -> None:
    ${downgrades if downgrades else "pass"}
'''


class MigrationError(Exception):
    pass


def async_url(url: str) -> str:
    """Any Postgres URL to the asyncpg driver URL SQLAlchemy needs."""
    parsed = make_url(url)
    if parsed.drivername in ("postgresql", "postgres"):
        parsed = parsed.set(drivername="postgresql+asyncpg")
    return parsed.render_as_string(hide_password=False)


def config(app: App, url: str) -> Config:
    cfg = Config(stdout=io.StringIO())  # Alembic's own chatter; our CLI reports instead
    cfg.set_main_option("script_location", str(app.migrations_dir))
    cfg.set_main_option("sqlalchemy.url", async_url(url))
    cfg.set_main_option("file_template", "%%(rev)s_%%(slug)s")
    cfg.attributes["app"] = app
    return cfg


def ensure_initialised(app: App) -> None:
    """Create the migrations directory, ``env.py`` and the script template
    if they do not exist. Idempotent."""
    root = app.migrations_dir
    (root / "versions").mkdir(parents=True, exist_ok=True)
    env = root / "env.py"
    if not env.exists():
        env.write_text(ENV_PY)
    mako = root / "script.py.mako"
    if not mako.exists():
        mako.write_text(SCRIPT_MAKO)


def makemigration(app: App, url: str, message: str, *, empty: bool = False) -> Path:
    """Write a new migration and return its path. With ``empty`` the file has
    empty ``upgrade`` and ``downgrade`` for hand-written SQL; otherwise it is
    autogenerated from the difference between entities and the database."""
    ensure_initialised(app)
    before = set(_versions(app))
    try:
        command.revision(config(app, url), message=message, autogenerate=not empty)
    except CommandError as exc:
        raise MigrationError(str(exc)) from exc
    new = set(_versions(app)) - before
    if len(new) != 1:
        raise MigrationError("expected exactly one new migration file")
    path = new.pop()
    logger.info("migration written path=%s", path)
    return path


def migrate(app: App, url: str) -> None:
    """Apply every pending migration."""
    ensure_initialised(app)
    try:
        command.upgrade(config(app, url), "head")
    except CommandError as exc:
        raise MigrationError(str(exc)) from exc
    logger.info("migrated app=%s", app.package)


def check(app: App, url: str) -> None:
    """Raise ``MigrationError`` if entities differ from what the migration
    chain produces. The database must already be migrated to head."""
    ensure_initialised(app)
    try:
        command.check(config(app, url))
    except AutogenerateDiffsDetected as exc:
        raise MigrationError(f"entities differ from migrations: {exc}") from exc
    except CommandError as exc:
        raise MigrationError(str(exc)) from exc


def _versions(app: App) -> list[Path]:
    return sorted((app.migrations_dir / "versions").glob("*.py"))


def _include_object(
    obj: Any, name: str | None, type_: str, reflected: bool, compare_to: Any
) -> bool:
    return type_ in ("table", "column")


def run_env(context: Any) -> None:
    """The body of every app's ``env.py``. ``context`` is Alembic's
    ``alembic.context`` proxy module, which behaves as an
    ``EnvironmentContext`` while a script runs. Reads the App from the config
    and runs the migrations against its metadata over an async engine."""
    app: App = context.config.attributes["app"]
    metadata = app.metadata
    url = context.config.get_main_option("sqlalchemy.url")
    assert url is not None

    def run_sync(connection: Connection) -> None:
        context.configure(
            connection=connection,
            target_metadata=metadata,
            include_object=_include_object,
            compare_type=True,
        )
        with context.begin_transaction():
            context.run_migrations()

    async def run_async() -> None:
        engine = create_async_engine(url)
        try:
            async with engine.connect() as connection:
                await connection.run_sync(run_sync)
                await connection.commit()
        finally:
            await engine.dispose()

    if context.is_offline_mode():
        context.configure(url=url, target_metadata=metadata, include_object=_include_object)
        with context.begin_transaction():
            context.run_migrations()
        return
    asyncio.run(run_async())
